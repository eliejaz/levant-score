pub fn get(code: &str) -> Preset {
    all()
        .into_iter()
        .find(|p| p.code == code)
        .unwrap_or_else(|| all().pop().unwrap())
}

#[allow(clippy::too_many_arguments)]
fn preset(
    code: &'static str,
    name: &'static str,
    name_ar: &'static str,
    description: &'static str,
    description_ar: &'static str,
    team_mode: bool,
    allowed: Vec<i32>,
    direction: ScoreDirection,
    default_target: Option<i32>,
    threshold_rule: ThresholdRule,
    score_mode: ScoreMode,
    round_limit: Option<i32>,
    rule: &'static str,
    rule_ar: &'static str,
    accent: &'static str,
) -> Preset {
    Preset {
        code,
        name,
        name_ar,
        description,
        description_ar,
        team_mode,
        min_players: *allowed.first().unwrap(),
        max_players: *allowed.last().unwrap(),
        allowed_player_counts: allowed,
        direction,
        default_target,
        threshold_rule,
        score_mode,
        round_limit,
        rule,
        rule_ar,
        accent,
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn reviewed_player_counts_match_java_contract() {
        let expected = [
            ("leekha-solo", vec![4]),
            ("leekha-team", vec![4]),
            ("400", vec![4]),
            ("tarneeb", vec![4]),
            ("chinese", vec![2, 3, 4]),
            ("trex", vec![4]),
            ("trex-complex", vec![4]),
            ("belote", vec![4]),
            ("basra", vec![2, 4]),
            ("hand", vec![2, 3, 4]),
            ("custom", (2..=12).collect()),
        ];
        for (code, counts) in expected {
            assert_eq!(get(code).allowed_player_counts, counts);
        }
    }
    #[test]
    fn tarneeb_target_is_31() {
        assert_eq!(get("tarneeb").default_target, Some(31));
    }
}
